import { useState } from "react";

/**
 * Проигрывать ли вступительную анимацию главной страницы.
 *
 * Каскад появления блоков нужен один раз — при первом открытии главной.
 * Раньше при каждом переключении режима «обход / VPN» поддерево пересоздавалось
 * и анимация проигрывалась заново: панель дёргалась каскадом поверх
 * перекрёстного затухания.
 *
 * Флаг живёт в модуле, а не в компоненте, намеренно: переключение режима не
 * размонтирует страницу, поэтому состояние хука его бы не поймало.
 */
let introPlayed = false;

export function useDashboardIntro(): boolean {
  const [intro] = useState(() => {
    if (introPlayed) {
      return false;
    }

    introPlayed = true;

    return true;
  });

  return intro;
}

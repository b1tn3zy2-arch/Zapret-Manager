// Подключаем useEffect для управления таймером и useState для хранения результата.
import { useEffect, useState } from "react";
// — разделитель: после импорта объявляется сам хук —
// Экспортируем дженерик-хук useDebounce: возвращает значение с задержкой.
// Параметры: value — исходное значение, delay — задержка в миллисекундах.
export function useDebounce<T>(value: T, delay: number): T {
  // Создаём состояние с начальным значением, чтобы первый рендер не был пустым.
  const [debounced, setDebounced] = useState(value);
  // — разделитель: состояние объявлено, настраиваем эффект —
  // Эффект перезапускается при каждом изменении value или delay.
  useEffect(() => {
    // Планируем обновление состояния через timeout; при новом значении старый сбросится.
    const timer = window.setTimeout(() => {
      // По истечении задержки фиксируем последнее значение в состоянии.
      setDebounced(value);
      // Продолжаем предыдущую конструкцию.
    }, delay);
    // — разделитель: таймер создан, описываем его очистку —
    // Функция очистки отменяет не сработавший таймер при размонтировании или ре-ране.
    return () => {
      // Гарантированно снимаем таймер, чтобы не осталось «висячих» обновлений.
      window.clearTimeout(timer);
      // Продолжаем предыдущую конструкцию.
    };
    // Закрываем функцию очистки эффекта.
  }, [value, delay]);
  // Закрываем вызов useEffect и его список зависимостей.
  // — разделитель: эффект настроен, возвращаем результат —
  // Возвращаем последнее установленное значение с задержкой.
  return debounced;
  // Продолжаем предыдущую конструкцию.
}
// Закрываем тело хука useDebounce.

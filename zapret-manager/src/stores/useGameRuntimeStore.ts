// Импортируем зависимости из модуля zustand.
import { create } from "zustand";
// Импортируем зависимости из модуля zustand/middleware.
import { persist } from "zustand/middleware";
// Импортируем зависимости из модуля zustand/middleware/immer.
import { immer } from "zustand/middleware/immer";
// — разделитель логических блоков —

// Обрабатываем конструкцию: export.
export interface GameRuntimeStoreState {
  // Сохраняем пояснение разработчика: id игры -> дерево процессов, которое было выдано при запуске
  /** id игры -> дерево процессов, которое было выдано при запуске */
  // Обрабатываем конструкцию: running.
  running: Record<string, number[]>;
  // Сохраняем пояснение разработчика:
  /**
   // Сохраняем пояснение разработчика: * id игры -> true, если игра запущена, но приложение её не з…
   * id игры -> true, если игра запущена, но приложение её не запускало.
   // Сохраняем пояснение разработчика: *
   *
   // Сохраняем пояснение разработчика: * Такие игры находятся по пути к исполняемому файлу: их не в…
   * Такие игры находятся по пути к исполняемому файлу: их не видно
   // Сохраняем пояснение разработчика: * в дереве процессов, а закрыть их из приложения тоже нужно.
   * в дереве процессов, а закрыть их из приложения тоже нужно.
   // Сохраняем пояснение разработчика: 
   */
  // Обрабатываем конструкцию: runningByPath.
  runningByPath: Record<string, boolean>;
  // Обрабатываем конструкцию: startedAt.
  startedAt: Record<string, number>;
  // Обрабатываем конструкцию: markRunning.
  markRunning: (gameId: string, pids: readonly number[]) => void;
  // Обрабатываем конструкцию: markStopped.
  markStopped: (gameId: string) => void;
  // Сохраняем пояснение разработчика: Отмечает игру, найденную по пути к исполняемому файлу.
  /** Отмечает игру, найденную по пути к исполняемому файлу. */
  // Обрабатываем конструкцию: markRunningByPath.
  markRunningByPath: (gameId: string) => void;
  // Сохраняем пояснение разработчика: Игра по пути больше не работает: защёлка снимается.
  /** Игра по пути больше не работает: защёлка снимается. */
  // Обрабатываем конструкцию: clearRunningByPath.
  clearRunningByPath: (gameId: string) => void;
  // Обрабатываем конструкцию: pidsOf.
  pidsOf: (gameId: string) => number[];
  // Обрабатываем конструкцию: isRunning.
  isRunning: (gameId: string) => boolean;
  // Обрабатываем конструкцию: clearAll.
  clearAll: () => void;
  // Закрываем текущий блок.
}
// — разделитель логических блоков —

// Сохраняем пояснение разработчика:
/**
 // Сохраняем пояснение разработчика: * Состояние запущенных игр живёт в отдельном сторе с persist…
 * Состояние запущенных игр живёт в отдельном сторе с persist.
 // Сохраняем пояснение разработчика: *
 *
 // Сохраняем пояснение разработчика: * Раньше оно было локальным состоянием хука, который жил тол…
 * Раньше оно было локальным состоянием хука, который жил только на странице
 // Сохраняем пояснение разработчика: * «Игры»: переход на другую страницу или перезапуск приложен…
 * «Игры»: переход на другую страницу или перезапуск приложения стирали его, и
 // Сохраняем пояснение разработчика: * игра продолжала работать без кнопки «Закрыть игру». Хранит…
 * игра продолжала работать без кнопки «Закрыть игру». Хранится дерево
 // Сохраняем пояснение разработчика: * процессов, потому что у игр с античитом PID лаунчера умира…
 * процессов, потому что у игр с античитом PID лаунчера умирает сразу.
 // Сохраняем пояснение разработчика: 
 */
// Обрабатываем конструкцию: export.
export const useGameRuntimeStore = create<GameRuntimeStoreState>()(
  // Обрабатываем конструкцию: persist.
  persist(
    // Обрабатываем конструкцию: immer.
    immer((set, get) => ({
      // Обрабатываем конструкцию: running.
      running: {},
      // Обрабатываем конструкцию: runningByPath.
      runningByPath: {},
      // Обрабатываем конструкцию: startedAt.
      startedAt: {},
      // — разделитель логических блоков —

      // Обрабатываем конструкцию: markRunning.
      markRunning: (gameId, pids) =>
        // Обрабатываем конструкцию: set.
        set((state) => {
          // Обрабатываем конструкцию: state.
          state.running[gameId] = [...pids];
          // Обрабатываем конструкцию: state.
          state.startedAt[gameId] = Date.now();
          // Обрабатываем конструкцию: delete state.runningByPath[gameId].
          delete state.runningByPath[gameId];
          // Закрываем текущий блок.
        }),
      // — разделитель логических блоков —

      // Обрабатываем конструкцию: markStopped.
      markStopped: (gameId) =>
        // Обрабатываем конструкцию: set.
        set((state) => {
          // Обрабатываем конструкцию: delete state.running[gameId].
          delete state.running[gameId];
          // Обрабатываем конструкцию: delete state.startedAt[gameId].
          delete state.startedAt[gameId];
          // Обрабатываем конструкцию: delete state.runningByPath[gameId].
          delete state.runningByPath[gameId];
          // Закрываем текущий блок.
        }),
      // — разделитель логических блоков —

      // Обрабатываем конструкцию: markRunningByPath.
      markRunningByPath: (gameId) =>
        // Обрабатываем конструкцию: set.
        set((state) => {
          // Обрабатываем конструкцию: state.
          state.runningByPath[gameId] = true;
          // Закрываем текущий блок.
        }),
      // — разделитель логических блоков —

      // Обрабатываем конструкцию: clearRunningByPath.
      clearRunningByPath: (gameId) =>
        // Обрабатываем конструкцию: set.
        set((state) => {
          // Обрабатываем конструкцию: delete state.runningByPath[gameId].
          delete state.runningByPath[gameId];
          // Закрываем текущий блок.
        }),
      // — разделитель логических блоков —

      // Обрабатываем конструкцию: pidsOf.
      pidsOf: (gameId) => get().running[gameId] ?? [],
      // — разделитель логических блоков —

      // Обрабатываем конструкцию: isRunning.
      isRunning: (gameId) =>
        // Обрабатываем конструкцию: (get().running[gameId]?.length ?? 0).
        (get().running[gameId]?.length ?? 0) > 0 ||
        // Обрабатываем конструкцию: get.
        get().runningByPath[gameId] === true,
      // — разделитель логических блоков —

      // Обрабатываем конструкцию: clearAll.
      clearAll: () =>
        // Обрабатываем конструкцию: set.
        set((state) => {
          // Обрабатываем конструкцию: state.
          state.running = {};
          // Обрабатываем конструкцию: state.
          state.runningByPath = {};
          // Обрабатываем конструкцию: state.
          state.startedAt = {};
          // Закрываем текущий блок.
        }),
      // Закрываем текущий блок.
    })),
    // Открываем объектный литерал.
    {
      // Обрабатываем конструкцию: name.
      name: "zapret-manager:game-runtime",
      // Обрабатываем конструкцию: partialize.
      partialize: (state) => ({
        // Обрабатываем конструкцию: running.
        running: state.running,
        // Обрабатываем конструкцию: runningByPath.
        runningByPath: state.runningByPath,
        // Обрабатываем конструкцию: startedAt.
        startedAt: state.startedAt,
        // Закрываем текущий блок.
      }),
      // Закрываем текущий блок.
    }
    // Закрываем выражение или список аргументов.
  )
  // Закрываем выражение или список аргументов.
);
// — разделитель логических блоков —

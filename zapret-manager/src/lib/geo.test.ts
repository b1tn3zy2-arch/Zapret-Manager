// Импортируем зависимости из модуля vitest.
import { describe, expect, it } from "vitest";
// — разделитель логических блоков —

// Импортируем зависимости из модуля @/lib/geo.
import {
  // Подключаем именованный импорт countryCodeToFlagSrc.
  countryCodeToFlagSrc,
  // Подключаем именованный импорт getGreeting.
  getGreeting,
  // Подключаем именованный импорт hasFlagAsset.
  hasFlagAsset,
  // Подключаем именованный импорт isKnownCountryCode.
  isKnownCountryCode,
  // Подключаем именованный импорт toCountryCode.
  toCountryCode,
  // Закрываем текущий блок.
} from "@/lib/geo";
// — разделитель логических блоков —

// Обрабатываем конструкцию: describe.
describe("getGreeting", () => {
  // Обрабатываем конструкцию: it.
  it("по всем часам суток возвращает одну из четырёх приветствий", () => {
    // Обрабатываем конструкцию: const variants = new Set<string>().
    const variants = new Set<string>();
    // — разделитель логических блоков —

    // Запускаем цикл с инициализацией, условием и шагом.
    for (let hour = 0; hour < 24; hour += 1) {
      // Обрабатываем конструкцию: variants.
      variants.add(getGreeting(new Date(2026, 0, 1, hour)));
      // Закрываем текущий блок.
    }
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect([...variants].sort()).toEqual([
      // Обрабатываем конструкцию: Доброе утро.
      "Доброе утро",
      // Обрабатываем конструкцию: Доброй ночи.
      "Доброй ночи",
      // Обрабатываем конструкцию: Добрый вечер.
      "Добрый вечер",
      // Обрабатываем конструкцию: Добрый день.
      "Добрый день",
      // Закрываем массив или список.
    ]);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it.each([
    // Открываем массив.
    [0, "Доброй ночи"],
    // Открываем массив.
    [4, "Доброй ночи"],
    // Открываем массив.
    [5, "Доброе утро"],
    // Открываем массив.
    [9, "Доброе утро"],
    // Открываем массив.
    [11, "Доброе утро"],
    // Открываем массив.
    [12, "Добрый день"],
    // Открываем массив.
    [15, "Добрый день"],
    // Открываем массив.
    [17, "Добрый день"],
    // Открываем массив.
    [18, "Добрый вечер"],
    // Открываем массив.
    [22, "Добрый вечер"],
    // Открываем массив.
    [23, "Доброй ночи"],
    // Закрываем массив или список.
  ])("в %i:00 возвращает «%s»", (hour, expected) => {
    // Обрабатываем конструкцию: expect.
    expect(getGreeting(new Date(2026, 0, 1, hour))).toBe(expected);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("начинается со слова Добр, чтобы находиться в UI одним селектором", () => {
    // Запускаем цикл с инициализацией, условием и шагом.
    for (let hour = 0; hour < 24; hour += 1) {
      // Обрабатываем конструкцию: expect.
      expect(getGreeting(new Date(2026, 0, 1, hour))).toMatch(/^Добр/);
      // Закрываем текущий блок.
    }
    // Закрываем текущий блок.
  });
  // Закрываем текущий блок.
});
// — разделитель логических блоков —

// Обрабатываем конструкцию: describe.
describe("toCountryCode", () => {
  // Обрабатываем конструкцию: it.
  it("приводит код к верхнему регистру", () => {
    // Обрабатываем конструкцию: expect.
    expect(toCountryCode("ru")).toBe("RU");
    // Обрабатываем конструкцию: expect.
    expect(toCountryCode(" de ")).toBe("DE");
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("возвращает null для некорректного значения", () => {
    // Обрабатываем конструкцию: expect.
    expect(toCountryCode("")).toBeNull();
    // Обрабатываем конструкцию: expect.
    expect(toCountryCode("rus")).toBeNull();
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("отбрасывает коды без флага", () => {
    // Обрабатываем конструкцию: expect.
    expect(toCountryCode("zz")).toBeNull();
    // Обрабатываем конструкцию: expect.
    expect(isKnownCountryCode("RU")).toBe(true);
    // Обрабатываем конструкцию: expect.
    expect(hasFlagAsset("RU")).toBe(true);
    // Обрабатываем конструкцию: expect.
    expect(hasFlagAsset("zz")).toBe(false);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("отдаёт флаг инлайном, а для неизвестного кода — флаг-заглушку", () => {
    // Обрабатываем конструкцию: const ru = countryCodeToFlagSrc(RU).
    const ru = countryCodeToFlagSrc("RU");
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(ru).toMatch(/^data:image\/svg\+xml/);
    // Обрабатываем конструкцию: expect.
    expect(countryCodeToFlagSrc("zz")).not.toBe(ru);
    // Закрываем текущий блок.
  });
  // Закрываем текущий блок.
});
// — разделитель логических блоков —

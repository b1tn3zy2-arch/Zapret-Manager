// Обрабатываем конструкцию: describe.
describe("parseDomainsFromText", () => {
  // Обрабатываем конструкцию: it.
  it("пропускает комментарии и пустые строки", () => {
    // Обрабатываем конструкцию: const text = [ # список, , discord.com, youtube.com , n….
    const text = [
      // Обрабатываем конструкцию: # список.
      "# список",
      // Обрабатываем конструкцию: .
      "",
      // Обрабатываем конструкцию: discord.com.
      "discord.com",
      // Обрабатываем конструкцию: youtube.com.
      "  youtube.com  ",
      // Обрабатываем конструкцию: not a domain.
      "not a domain",
      // Закрываем массив или список.
    ].join("\n");
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(parseDomainsFromText(text)).toEqual(["discord.com", "youtube.com"]);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("убирает дубликаты, сохраняя порядок", () => {
    // Обрабатываем конструкцию: expect.
    expect(parseDomainsFromText("a.com\nb.com\na.com")).toEqual([
      // Обрабатываем конструкцию: a.com.
      "a.com",
      // Обрабатываем конструкцию: b.com.
      "b.com",
      // Закрываем массив или список.
    ]);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("пустой текст даёт пустой массив", () => {
    // Обрабатываем конструкцию: expect.
    expect(parseDomainsFromText("")).toEqual([]);
    // Обрабатываем конструкцию: expect.
    expect(parseDomainsFromText("\n\n")).toEqual([]);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("отбрасывает домены с недопустимыми символами", () => {
    // Обрабатываем конструкцию: expect.
    expect(parseDomainsFromText("bad domain.com\nok.com\n")).toEqual([
      // Обрабатываем конструкцию: ok.com.
      "ok.com",
      // Закрываем массив или список.
    ]);
    // Закрываем текущий блок.
  });
  // Закрываем текущий блок.
});

// Импортируем зависимости из модуля vitest.
import { describe, expect, it } from "vitest";
// — разделитель логических блоков —

// Импортируем зависимости из модуля @/lib/smoothPath.
import { buildAreaPath, buildSmoothPath } from "@/lib/smoothPath";
// — разделитель логических блоков —

// Обрабатываем конструкцию: describe.
describe("buildSmoothPath", () => {
  // Обрабатываем конструкцию: it.
  it("returns empty string for fewer than two points", () => {
    // Обрабатываем конструкцию: expect.
    expect(buildSmoothPath([])).toBe("");
    // Обрабатываем конструкцию: expect.
    expect(buildSmoothPath([{ x: 1, y: 2 }])).toBe("");
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("starts at the first point", () => {
    // Обрабатываем конструкцию: const path = buildSmoothPath([ { x: 0, y: 10 }, { x: 10….
    const path = buildSmoothPath([
      // Открываем объектный литерал.
      { x: 0, y: 10 },
      // Открываем объектный литерал.
      { x: 10, y: 20 },
      // Закрываем массив или список.
    ]);
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(path.startsWith("M 0.00 10.00")).toBe(true);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("uses cubic bezier segments between points", () => {
    // Обрабатываем конструкцию: const path = buildSmoothPath([ { x: 0, y: 10 }, { x: 10….
    const path = buildSmoothPath([
      // Открываем объектный литерал.
      { x: 0, y: 10 },
      // Открываем объектный литерал.
      { x: 10, y: 20 },
      // Открываем объектный литерал.
      { x: 20, y: 5 },
      // Закрываем массив или список.
    ]);
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(path.match(/ C /g)).toHaveLength(2);
    // Обрабатываем конструкцию: expect.
    expect(path.endsWith("20.00 5.00")).toBe(true);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("stays within the vertical bounds of neighbouring points", () => {
    // Обрабатываем конструкцию: const path = buildSmoothPath([ { x: 0, y: 100 }, { x: 1….
    const path = buildSmoothPath([
      // Открываем объектный литерал.
      { x: 0, y: 100 },
      // Открываем объектный литерал.
      { x: 10, y: 0 },
      // Открываем объектный литерал.
      { x: 20, y: 100 },
      // Закрываем массив или список.
    ]);
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: const numbers = path .split(/[^\d.-]+/) .filter((token)….
    const numbers = path
      // Продолжаем цепочку вызовов.
      .split(/[^\d.-]+/)
      // Продолжаем цепочку вызовов.
      .filter((token) => token !== "" && token !== "-")
      // Продолжаем цепочку вызовов.
      .map(Number);
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(numbers.every((value) => value >= 0 && value <= 100)).toBe(true);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("formats every coordinate with two decimals", () => {
    // Обрабатываем конструкцию: const path = buildSmoothPath([ { x: 0, y: 1.234567 }, {….
    const path = buildSmoothPath([
      // Открываем объектный литерал.
      { x: 0, y: 1.234567 },
      // Открываем объектный литерал.
      { x: 10.98765, y: 2 },
      // Открываем объектный литерал.
      { x: 20.12345, y: 3 },
      // Закрываем массив или список.
    ]);
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: const coords = path.match(/-?\d+\.\d+/g) ?? [].
    const coords = path.match(/-?\d+\.\d+/g) ?? [];
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(coords.length).toBeGreaterThan(0);
    // Обрабатываем конструкцию: expect.
    expect(
      // Обрабатываем конструкцию: coords.
      coords.every((coord) => {
        // Обрабатываем конструкцию: const [, decimals] = coord.split(.).
        const [, decimals] = coord.split(".");
        // Возвращаем результат: decimals !== undefined && decimals.length === 2.
        return decimals !== undefined && decimals.length === 2;
        // Закрываем текущий блок.
      })
      // Закрываем выражение или список аргументов.
    ).toBe(true);
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("keeps control points near the data when tension is small", () => {
    // Обрабатываем конструкцию: const path = buildSmoothPath( [ { x: 0, y: 0 }, { x: 10….
    const path = buildSmoothPath(
      // Открываем массив.
      [
        // Открываем объектный литерал.
        { x: 0, y: 0 },
        // Открываем объектный литерал.
        { x: 10, y: 10 },
        // Открываем объектный литерал.
        { x: 20, y: 0 },
        // Закрываем массив или список.
      ],
      // Обрабатываем конструкцию: 0.
      0
      // Закрываем выражение или список аргументов.
    );
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(path).toBe(
      // Обрабатываем конструкцию: M 0.00 0.00 C 0.00 0.00, 10.00 10.00, 10.00 10.00 C 10.….
      "M 0.00 0.00 C 0.00 0.00, 10.00 10.00, 10.00 10.00 C 10.00 10.00, 20.00 0.00, 20.00 0.00"
      // Закрываем выражение или список аргументов.
    );
    // Закрываем текущий блок.
  });
  // Закрываем текущий блок.
});
// — разделитель логических блоков —

// Обрабатываем конструкцию: describe.
describe("buildAreaPath", () => {
  // Обрабатываем конструкцию: it.
  it("returns empty string when there is nothing to fill", () => {
    // Обрабатываем конструкцию: expect.
    expect(buildAreaPath([], 50)).toBe("");
    // Обрабатываем конструкцию: expect.
    expect(buildAreaPath([{ x: 1, y: 2 }], 50)).toBe("");
    // Закрываем текущий блок.
  });
  // — разделитель логических блоков —

  // Обрабатываем конструкцию: it.
  it("closes the curve down to the baseline", () => {
    // Обрабатываем конструкцию: const path = buildAreaPath( [ { x: 0, y: 10 }, { x: 10,….
    const path = buildAreaPath(
      // Открываем массив.
      [
        // Открываем объектный литерал.
        { x: 0, y: 10 },
        // Открываем объектный литерал.
        { x: 10, y: 20 },
        // Закрываем массив или список.
      ],
      // Обрабатываем конструкцию: 40.
      40
      // Закрываем выражение или список аргументов.
    );
    // — разделитель логических блоков —

    // Обрабатываем конструкцию: expect.
    expect(path.endsWith("L 10.00 40.00 L 0.00 40.00 Z")).toBe(true);
    // Обрабатываем конструкцию: expect.
    expect(path.startsWith("M 0.00 10.00")).toBe(true);
    // Закрываем текущий блок.
  });
  // Закрываем текущий блок.
});
